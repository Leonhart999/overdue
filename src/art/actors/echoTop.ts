const WALK_TOP = 14;

function frame(dir: Dir, fr: Frame): PixBuf {
  const idle = grid(IDLE[dir], LG, `pc_echo/${dir}`);
  if (fr === 'idle') return idle.outline(C.ink);
  // stride: head, collar and shoulders drop 1px (body bob), the rest comes from the walk grid
  const b = new PixBuf(PC_W, PC_H);
  b.blit(idle.crop(0, 0, PC_W, WALK_TOP - 1), 0, 1);
  b.blit(grid(WALK[dir][fr], LG, `pc_echo/${dir}_${fr}`), 0, WALK_TOP);
  return b.outline(C.ink);
}

function anims(): AnimSpec[] {
  const idx = (d: Dir, f: Frame) => DIRS.indexOf(d) * 3 + FRAMES.indexOf(f);
  return DIRS.flatMap((d) => [
    { key: `pc_echo_idle_${d}`, frames: [idx(d, 'idle')], frameRate: 1, repeat: 0 },
    { key: `pc_echo_walk_${d}`, frames: [idx(d, 'walkA'), idx(d, 'idle'), idx(d, 'walkB'), idx(d, 'idle')], frameRate: 8, repeat: -1 },
  ]);
}

export function buildEchoTopSheet(): SheetSpec {
  const frames: { name: string; buf: PixBuf }[] = [];
  for (const d of DIRS) for (const f of FRAMES) frames.push({ name: `${d}_${f}`, buf: frame(d, f) });
  return {
    key: 'pc_echo', group: 'Player', frameW: PC_W, frameH: PC_H, columns: 12, frames, anims: anims(),
    meta: { origin: [0.5, 1], note: 'Feet on row 28, outline on row 29. Hands on rows 20-21 (~9px above the feet).' },
  };
}
