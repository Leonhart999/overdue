/** Lift one leg (front/back views): columns x0..x1 of rows top..28 move up 1px. */
function liftLeg(b: PixBuf, x0: number, x1: number, top: number): void {
  for (let x = x0; x <= x1; x++) {
    for (let y = top; y < PC_H - 2; y++) b.set(x, y, b.get(x, y + 1));
    b.set(x, PC_H - 2, 0);
  }
}

function replaceRows(b: PixBuf, top: number, rows: PixBuf): void {
  b.rect(0, top, PC_W, rows.h, 0);
  b.blit(rows, 0, top);
}

function frame(dir: Dir, fr: (typeof FRAMES)[number]): PixBuf {
  let b: PixBuf;
  if (dir === 'down' || dir === 'up') {
    b = grid(dir === 'down' ? DOWN : UP, BASE, `pc_echo/${dir}`);
    // walk: one foot lifts, the body dips a pixel on the passing frame
    if (fr === 'walkA') liftLeg(b, 5, 9, 22);
    if (fr === 'walkB') liftLeg(b, 10, 14, 22);
  } else {
    const lg = dir === 'left' ? LEFT : RIGHT;
    b = grid(SIDE, lg, `pc_echo/${dir}`);
    if (fr !== 'idle') {
      replaceRows(b, SIDE_LEGS_TOP, grid(fr === 'walkA' ? SIDE_WALK_A : SIDE_WALK_B, lg, `pc_echo/${dir}_${fr}`));
      // the stride frame drops the upper body by a pixel
      if (fr === 'walkA') b.shiftRegion(0, 0, PC_W, SIDE_LEGS_TOP, 0, 1);
    }
    if (dir === 'right') b = b.flipX();
  }
  return b.outline(C.ink);
}

function anims(): AnimSpec[] {
  const idx = (d: Dir, f: (typeof FRAMES)[number]) => DIRS.indexOf(d) * 3 + FRAMES.indexOf(f);
  return DIRS.flatMap((d) => [
    { key: `pc_echo_idle_${d}`, frames: [idx(d, 'idle')], frameRate: 1, repeat: 0 },
    { key: `pc_echo_walk_${d}`, frames: [idx(d, 'walkA'), idx(d, 'idle'), idx(d, 'walkB'), idx(d, 'idle')], frameRate: 8, repeat: -1 },
  ]);
}

export function buildEchoTopSheet(): SheetSpec {
  const frames: { name: string; buf: PixBuf }[] = [];
  for (const d of DIRS) for (const f of FRAMES) frames.push({ name: `${d}_${f}`, buf: frame(d, f) });
  return {
    key: 'pc_echo', group: 'Player', frameW: PC_W, frameH: PC_H, columns: 12, frames, anims: anims(),
    meta: { origin: [0.5, 1], note: 'Feet on row 28, outline on row 29. Hands on rows 20-21 (~9px above the feet).' },
  };
}
