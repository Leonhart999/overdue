/**
 * Overworld character sprites: 16x24 frames, 3/4 top-down view.
 *
 * Each character is authored as three hand-drawn idle grids (down / up / left) using semantic
 * letters; a per-character legend maps the letters to palette colours. Walk frames are derived:
 *  - down/up: one leg is lifted by one pixel (walkA = viewer-left leg, walkB = viewer-right leg)
 *  - left: the leg rows are replaced by stride templates
 *  - right: mirror of left, optionally re-coloured (e.g. Echo's chrome arm is on the left side)
 * A 1px ink outline is added automatically, so grids leave a 1px transparent border.
 *
 * Semantic letters (shared by all characters, mapped by their legend):
 *   H h l  hair dark/mid/light      S s z  skin light/mid/shadow     e  eye
 *   J j i  main garment d/m/l       K k    second garment d/m        c C  accent bright/dark
 *   M m n  metal d/m/l              P p    pants d/m                 B b  boots d/l
 *   x y Y  extra details            R r    visor red/light           w  white/highlight
 *   o      ink
 */
import { C } from '../palette';
import { grid, Legend } from '../core/grid';
import { PixBuf } from '../core/pixbuf';
import { AnimSpec, SheetSpec } from '../core/sheet';

export const OW_W = 16;
export const OW_H = 24;
export const OW_DIRS = ['down', 'left', 'right', 'up'] as const;
export type OwDir = (typeof OW_DIRS)[number];
export const OW_FRAMES = ['idle', 'walkA', 'walkB'] as const;

export interface OwCharDef {
  id: string;
  legend: Legend;
  /** Grids (strings, mapped by `legend`) or pre-rendered buffers (e.g. from the NPC generator). */
  down: string | PixBuf;
  up: string | PixBuf;
  left: string | PixBuf;
  /** Optional hand-authored right view; otherwise left is mirrored. */
  right?: string | PixBuf;
  /** Legend overrides applied to the mirrored right view (e.g. swap chrome arm for sleeve). */
  rightLegend?: Legend;
  /** First leg row for the down/up lift (rows legTop..22 of a leg column range move up 1px). */
  legTop: number;
  /** Side stride templates: rows `top`..22 for walkA and walkB (full 16-wide strings). */
  sideLegs: { top: number; walkA: string; walkB: string };
  /** Leg column ranges for down/up lifting, default [4,7] and [8,11]. */
  legCols?: [[number, number], [number, number]];
  /** Procedural extras drawn after the grid (before outline). */
  overlay?: (b: PixBuf, dir: OwDir) => void;
}

