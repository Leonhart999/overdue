// ---------------------------------------------------------------------------
// Frame derivation
// ---------------------------------------------------------------------------

function liftLeg(b: PixBuf, x0: number, x1: number, top: number): void {
  for (let x = x0; x <= x1; x++) {
    for (let y = top; y < OW_H - 1; y++) b.set(x, y, b.get(x, y + 1));
    b.set(x, OW_H - 1, 0);
  }
}

function replaceRows(b: PixBuf, top: number, rows: PixBuf): void {
  b.rect(0, top, OW_W, rows.h, 0);
  b.blit(rows, 0, top);
}

/** Build the 12 frames (4 directions x idle/walkA/walkB) for a character definition. */
export function buildOwFrames(def: OwCharDef): { name: string; buf: PixBuf }[] {
  const g = (src: string | PixBuf, lg: Legend, tag: string) =>
    typeof src === 'string' ? grid(src, lg, `${def.id}/${tag}`) : src.clone();
  const down = g(def.down, def.legend, 'down');
  const up = g(def.up, def.legend, 'up');
  const left = g(def.left, def.legend, 'left');
  const legsA = g(def.sideLegs.walkA, def.legend, 'legsA');
  const legsB = g(def.sideLegs.walkB, def.legend, 'legsB');
  const [lc, rc] = def.legCols ?? [[4, 7], [8, 11]];

  const frames: { name: string; buf: PixBuf }[] = [];
  const finish = (b: PixBuf, dir: OwDir) => {
    def.overlay?.(b, dir);
    return b.outline(C.ink);
  };

  for (const dir of OW_DIRS) {
    for (const fr of OW_FRAMES) {
      let b: PixBuf;
      if (dir === 'down' || dir === 'up') {
        b = (dir === 'down' ? down : up).clone();
        if (fr === 'walkA') liftLeg(b, lc[0], lc[1], def.legTop);
        if (fr === 'walkB') liftLeg(b, rc[0], rc[1], def.legTop);
      } else {
        let base: PixBuf;
        if (dir === 'right' && def.right) {
          base = g(def.right, def.legend, 'right');
        } else {
          const lg = dir === 'right' && def.rightLegend ? { ...def.legend, ...def.rightLegend } : def.legend;
          base = dir === 'left' ? left.clone() : g(def.left, lg, 'left').flipX();
        }
        if (fr !== 'idle') {
          const legs = fr === 'walkA' ? legsA : legsB;
          replaceRows(base, def.sideLegs.top, dir === 'right' ? legs.flipX() : legs);
          // stride frames bob down by a pixel at the hips
          if (fr === 'walkA') base.shiftRegion(0, 0, OW_W, def.sideLegs.top, 0, 1);
        }
        b = base;
      }
      frames.push({ name: `${dir}_${fr}`, buf: finish(b, dir) });
    }
  }
  return frames;
}

/** Frame index for (direction, frame). */
export function owIndex(dir: OwDir, frame: (typeof OW_FRAMES)[number]): number {
  return OW_DIRS.indexOf(dir) * 3 + OW_FRAMES.indexOf(frame);
}

export function owAnims(id: string): AnimSpec[] {
  const out: AnimSpec[] = [];
  for (const dir of OW_DIRS) {
    out.push({ key: `${id}_idle_${dir}`, frames: [owIndex(dir, 'idle')], frameRate: 1, repeat: 0 });
    out.push({ key: `${id}_walk_${dir}`, frames: [owIndex(dir, 'walkA'), owIndex(dir, 'idle'), owIndex(dir, 'walkB'), owIndex(dir, 'idle')], frameRate: 8, repeat: -1 });
  }
  return out;
}

export function owSheet(id: string, frames: { name: string; buf: PixBuf }[], group: string): SheetSpec {
  const key = `ow_${id}`;
  return {
    key, group, frameW: OW_W, frameH: OW_H, columns: 12, frames,
    anims: owAnims(id),
    meta: { origin: [0.5, 1], note: 'Feet touch the bottom pixel row. Use origin (0.5, 1) at the tile bottom-centre.' },
  };
}

export function buildMainCharacterSheets(): SheetSpec[] {
  return MAIN_CHARACTERS.map((d) => owSheet(d.id, buildOwFrames(d), 'Overworld: party'));
}
